create or replace function public.get_management_report_v89(p_month text,p_unit bigint default null) returns jsonb language plpgsql stable security definer set search_path=public,pg_temp as $$
declare v_from timestamptz;v_to timestamptz;v_result jsonb;
begin
 if not exists(select 1 from profiles where id=auth.uid() and active and role in ('leader','manager')) then raise exception 'Relatório permitido somente para dono e gestor.';end if;
 if p_month is null or p_month !~ '^[0-9]{4}-(0[1-9]|1[0-2])$' then raise exception 'Selecione um mês válido.';end if;
 if p_unit is not null and p_unit<>-1 and not exists(select 1 from barberxp_units where id=p_unit) then raise exception 'Unidade não encontrada.';end if;
 v_from:=(p_month||'-01')::timestamp at time zone 'America/Sao_Paulo';v_to:=((p_month||'-01')::date+interval '1 month') at time zone 'America/Sao_Paulo';
 with approved as (
 select a.*,coalesce(p.full_name,p.email,'Colaborador') as name,p.role as member_role,
 coalesce(a.metadata->>'financial_version'='84' and jsonb_typeof(a.metadata->'sale_price')='number' and jsonb_typeof(a.metadata->'cost_price')='number' and jsonb_typeof(a.metadata->'commission_amount')='number' and jsonb_typeof(a.metadata->'commission_percent')='number' and jsonb_typeof(a.metadata->'profit')='number',false) as has_financial
 from barber_actions a left join profiles p on p.id=a.user_id
 where a.status='approved' and a.created_at>=v_from and a.created_at<v_to
 and (p_unit is null or (p_unit=-1 and a.barberxp_unit_id is null) or a.barberxp_unit_id=p_unit)
 ),financial_sales as (
 select user_id,name,member_role,count(*) as sales,count(*) filter(where has_financial) as known_sales,count(*) filter(where not has_financial) as legacy_sales,
 sum(case when has_financial then (metadata->>'sale_price')::numeric else 0 end) as revenue,
 sum(case when has_financial then (metadata->>'cost_price')::numeric else 0 end) as cost,
 sum(case when has_financial then (metadata->>'commission_amount')::numeric else 0 end) as commission,
 sum(case when has_financial then (metadata->>'profit')::numeric else 0 end) as margin,
 coalesce(jsonb_agg(distinct (metadata->>'commission_percent')::numeric) filter(where has_financial),'[]'::jsonb) as rates
 from approved where action_key='produtos' group by user_id,name,member_role
 ),financial as (
 select * from financial_sales
 union all
 select p.id,coalesce(p.full_name,p.email,'Colaborador'),p.role,0::bigint,0::bigint,0::bigint,
 0::numeric,0::numeric,0::numeric,0::numeric,'[]'::jsonb
 from profiles p left join barberxp_member_units mu on mu.user_id=p.id
 where p.active and not exists(select 1 from financial_sales f where f.user_id=p.id)
 and (p_unit is null or (p_unit=-1 and mu.unit_id is null) or mu.unit_id=p_unit)
 ),production as (
 select p.id as user_id,coalesce(p.full_name,p.email,'Colaborador') as name,p.role,p.active,
 count(a.id) as actions,count(a.id) filter(where a.action_key='cortes') as cortes,count(a.id) filter(where a.action_key='barbas') as barbas,
 count(a.id) filter(where a.action_key='extras') as extras,count(a.id) filter(where a.action_key='produtos') as produtos,
 count(a.id) filter(where a.action_key='assinaturas') as assinaturas,count(a.id) filter(where a.action_key='reativacoes') as reativacoes,
 count(a.id) filter(where a.action_key not in ('cortes','barbas','extras','produtos','assinaturas','reativacoes')) as outras
 from profiles p left join approved a on a.user_id=p.id left join barberxp_member_units mu on mu.user_id=p.id
 where p.active or exists(select 1 from approved x where x.user_id=p.id)
 group by p.id,p.full_name,p.email,p.role,p.active,mu.unit_id
 having p_unit is null or count(a.id)>0 or (p_unit=-1 and mu.unit_id is null) or mu.unit_id=p_unit
 ) select jsonb_build_object('month',p_month,'unit_id',p_unit,
 'units',(select coalesce(jsonb_agg(to_jsonb(u) order by u.id),'[]'::jsonb) from barberxp_units u),
 'members',(select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'name',coalesce(p.full_name,p.email,'Colaborador'),'role',p.role,'active',p.active,'unit_id',mu.unit_id) order by p.full_name),'[]'::jsonb) from profiles p left join barberxp_member_units mu on mu.user_id=p.id),
 'professionals',(select coalesce(jsonb_agg(to_jsonb(f) order by f.revenue desc,f.name),'[]'::jsonb) from financial f),
 'production',(select coalesce(jsonb_agg(to_jsonb(p) order by p.name),'[]'::jsonb) from production p),
 'totals',(select jsonb_build_object('sales',coalesce(sum(sales),0),'known_sales',coalesce(sum(known_sales),0),'legacy_sales',coalesce(sum(legacy_sales),0),'revenue',coalesce(sum(revenue),0),'cost',coalesce(sum(cost),0),'commission',coalesce(sum(commission),0),'margin',coalesce(sum(margin),0)) from financial),
 'unassigned_actions',(select count(*) from approved where barberxp_unit_id is null)) into v_result;
 return v_result;
end;$$;
