  add column if not exists metadata jsonb not null default '{}'::jsonb;
alter table public.barber_actions
  add column if not exists review_reason text;

create table if not exists public.game_strategy (
  id smallint primary key default 1 check (id = 1),
  focus_mode text not null default 'auto' check (focus_mode in ('auto','produtos','extras','assinaturas')),
  monthly_product_profit_goal numeric(12,2) not null default 1000 check (monthly_product_profit_goal >= 0),
  weekly_bonus_easy integer not null default 3 check (weekly_bonus_easy >= 0),
  weekly_bonus_medium integer not null default 4 check (weekly_bonus_medium >= 0),
  weekly_bonus_hard integer not null default 5 check (weekly_bonus_hard >= 0),
  updated_by uuid references public.profiles(id),
  updated_at timestamptz not null default now()
);

insert into public.game_strategy(id) values (1) on conflict (id) do nothing;

create table if not exists public.member_game_settings (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  development boolean not null default false,
  joined_at date,
  updated_by uuid references public.profiles(id),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  sale_price numeric(12,2) not null default 0 check (sale_price >= 0),
  cost_price numeric(12,2) not null default 0 check (cost_price >= 0),
  active boolean not null default true,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.weekly_challenges (
  id bigint generated by default as identity primary key,
  week_start date not null,
  user_id uuid not null references public.profiles(id) on delete cascade,
  focus_key text not null check (focus_key in ('produtos','extras','assinaturas')),
  easy_target integer not null check (easy_target > 0),
  medium_target integer not null check (medium_target >= easy_target),
  hard_target integer not null check (hard_target >= medium_target),
  progress integer not null default 0 check (progress >= 0),
  bonus_awarded integer not null default 0 check (bonus_awarded >= 0),
  development boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (week_start,user_id)
);

